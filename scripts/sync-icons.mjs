/**
 * ColorFly: Icon sync script
 * 1. Scans src/webview/icon-pack/** (canonical, git-tracked copy of the icon set)
 *    and generates src/shared/iconCatalog.ts (all icons sorted by file name,
 *    assigned to one group).
 * 2. Copies the icon files into dist/icons so the webview can preview them.
 *
 * Usage: node scripts/sync-icons.mjs   (also runs automatically via `npm run build:ui`)
 */

import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceIconsDir = path.join(root, 'src', 'webview', 'icon-pack');
const distIconsDir = path.join(root, 'dist', 'icons');
const catalogFile = path.join(root, 'src', 'shared', 'iconCatalog.ts');

const ICON_GROUP = 'VS Code Icons';
const ALLOWED_EXTENSIONS = new Set(['.svg', '.png', '.jpg', '.jpeg', '.gif', '.webp', '.ico']);

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(fullPath)));
    } else if (ALLOWED_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
      files.push(fullPath);
    }
  }
  return files;
}

function toPosix(relativePath) {
  return relativePath.split(path.sep).join('/');
}

async function copyDir(src, dest) {
  await fs.mkdir(dest, { recursive: true });
  const entries = await fs.readdir(src, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      await copyDir(srcPath, destPath);
    } else if (ALLOWED_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
      await fs.copyFile(srcPath, destPath);
    }
  }
}

async function main() {
  const absoluteFiles = await walk(sourceIconsDir);

  const entries = absoluteFiles.map((absolutePath) => {
    const relative = toPosix(path.relative(sourceIconsDir, absolutePath));
    const fileName = path.basename(absolutePath);
    return { path: relative, fileName, group: ICON_GROUP };
  });

  entries.sort((a, b) => {
    const byName = a.fileName.toLowerCase().localeCompare(b.fileName.toLowerCase(), 'en');
    return byName !== 0 ? byName : a.path.localeCompare(b.path, 'en');
  });

  const seen = new Set();
  for (const entry of entries) {
    if (seen.has(entry.path)) {
      throw new Error(`Duplicate icon path generated: ${entry.path}`);
    }
    seen.add(entry.path);
  }

  const banner = `/**
 * AUTO-GENERATED by scripts/sync-icons.mjs — do not edit by hand.
 * Source: src/webview/icon-pack (${entries.length} icons, sorted by file name).
 */

export interface IconCatalogEntry {
  /** Path relative to vscode-iconn/icons (e.g. "abell.svg", "folders/git.svg"). */
  path: string;
  /** Bare file name (e.g. "abell.svg", "git.svg"). */
  fileName: string;
  /** Group this icon belongs to. */
  group: string;
}

/** Single group holding every icon collected from vscode-iconn/icons. */
export const ICON_GROUP = ${JSON.stringify(ICON_GROUP)};

export const ICON_CATALOG: IconCatalogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

  await fs.mkdir(path.dirname(catalogFile), { recursive: true });
  await fs.writeFile(catalogFile, banner, 'utf8');

  await fs.rm(distIconsDir, { recursive: true, force: true });
  await copyDir(sourceIconsDir, distIconsDir);

  const copied = (await walk(distIconsDir)).length;
  console.log(`icons:sync -> ${entries.length} catalog entries, ${copied} files copied to dist/icons`);
}

main().catch((error) => {
  console.error('icons:sync failed:', error);
  process.exit(1);
});
